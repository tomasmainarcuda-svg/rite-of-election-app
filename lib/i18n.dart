class I18n {
  final String lang;
  const I18n(this.lang);

  String t(String key, [Map<String, Object>? vars]) {
    var s = _strings[lang]?[key] ?? _strings['en']![key] ?? key;
    vars?.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
    return s;
  }

  String plural(String key, int n, [Map<String, Object>? vars]) => t('${key}_${n == 1 ? 'one' : 'other'}', {'n': n, ...?vars});

  String pick(L? o) => o == null ? '' : o.of(lang);

  /// Inline string for both languages: S('Close', 'Cerrar').
  String s(String en, String es) => lang == 'es' ? es : en;
}
